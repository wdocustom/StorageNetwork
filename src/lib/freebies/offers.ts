export type OfferKind = "meal" | "treat" | "extra";
export type MealSlot = "breakfast" | "lunch" | "dinner";
export type ExtraType = "haircut" | "carwash" | "voucher" | "discount";

/** What kind of OpenStreetMap place a brand match must be to count. */
export type PlaceType = "food" | "convenience" | "hairdresser" | "carwash" | "retail";

export interface Offer {
  id: string;
  /** Display name of the business. */
  brand: string;
  kind: OfferKind;
  /** Which meals this offer can stand in for (meals only). */
  mealSlots?: MealSlot[];
  extraType?: ExtraType;
  /** The freebie in a few words: "Free Original Grand Slam". */
  headline: string;
  /** The terms, in plain sentences. */
  details: string;
  /** Who qualifies. */
  eligibility: string;
  /**
   * Hours the planner may schedule an ARRIVAL, minutes after local midnight.
   * The end already leaves time to be seated and served.
   */
  window: [number, number];
  /** How the hours read to a person: "5 a.m. – noon". */
  windowNote: string;
  /** Minutes a visit takes. */
  dwell: number;
  dineIn: boolean;
  /** False for percent-off offers, which are listed but never called free. */
  free: boolean;
  /** Set when the freebie is (or can be) used on a later day. */
  redeemLater?: string;
  /** 3 = a full free meal / signature freebie, 1 = small or conditional. */
  priority: 1 | 2 | 3;
  /** A few words for the AI planner: cuisine / what it is. */
  tags: string;
  website: string;
  placeType: PlaceType;
  /** Matched against the OpenStreetMap `brand` (or `name`) tag. */
  match: RegExp;
  /** POSIX prefix for the Overpass query; `.` stands in for apostrophes. */
  osm: string;
  /** What to type into a place search when the brand name alone finds it better. */
  search?: string;
}

